#!/usr/bin/env python3
"""Compile led/sprites/*.txt into sprites.json (dashboard + agent) and sprites.h (MCU sketch).

Sprite file format:
    name: Ninja
    [run]            # 4+ frames, blank line between frames
    <8 rows of 13 chars: . = off, 1..3 = dim..bright>
    [sit]            # 2+ frames (breathing)
Animation skins (matrix, stars, fish, ants, meteor) come from src/overheard/ledanim.py and are appended after the characters.
Run with --check to fail if the generated files are stale (used by CI).
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "led", "sprites")
OUT_JSON = os.path.join(ROOT, "src", "overheard", "sprites.json")
OUT_H = os.path.join(ROOT, "led", "app", "sketch", "sprites.h")
sys.path.insert(0, os.path.join(ROOT, "src"))
from overheard import ledanim  # noqa: E402  (generated animation skins, appended after the characters)

W, H = 13, 8
LEVEL = {".": 0, "1": 70, "2": 150, "3": 255}


def _frame(path, sect, cur):
    if len(cur) != H or any(len(r) != W or set(r) - set(LEVEL) for r in cur):
        raise SystemExit("%s: bad frame in [%s]: need %d rows of %d chars from '.123'\n%s" % (path, sect, H, W, "\n".join(cur)))
    return cur


def parse(path):
    name, sect, frames, cur = None, None, {"run": [], "sit": []}, []
    for raw in open(path).read().splitlines() + [""]:
        ln = raw.strip()
        if ln and not ln.startswith("name:") and ln not in ("[run]", "[sit]"):
            cur.append(ln)
            continue
        if cur:                      # blank line or section header ends a frame
            frames[sect].append(_frame(path, sect, cur))
            cur = []
        if ln.startswith("name:"):
            name = ln[5:].strip()
        elif ln in ("[run]", "[sit]"):
            sect = ln[1:-1]
    if not name or len(frames["run"]) < 4 or len(frames["sit"]) < 2:
        raise SystemExit("%s: needs a name, >=4 run frames and >=2 sit frames" % path)
    return name, frames


def build():
    sprites = {}
    for fn in sorted(os.listdir(SRC)):
        if fn.endswith(".txt"):
            name, fr = parse(os.path.join(SRC, fn))
            sprites[fn[:-4]] = {"name": name, **fr}
    chars = list(sprites)
    anims = {}
    for aid, (aname, _gen) in ledanim.ANIMS.items():
        anims[aid] = ledanim.render(aid)
        sprites[aid] = {"name": aname, "anim": True, "run": anims[aid]}
    js = json.dumps(sprites, indent=1) + "\n"
    ids = list(sprites)
    h = ["// Generated by tools/build_sprites.py. Do not edit.", "#pragma once", "#include <stdint.h>", "",
         "#define SPRITE_COUNT %d   // all skins: characters first, then animations" % len(ids),
         "#define CHAR_COUNT %d" % len(chars), "#define ANIM_COUNT %d" % len(anims), "#define RUN_FRAMES 4", "#define SIT_FRAMES 2", "",
         "// [character][0..3 run, 4..5 sit][104 pixels, row-major 8x13]",
         "static const uint8_t SPRITES[CHAR_COUNT][6][104] = {"]
    for cid in chars:
        h.append("  { // %s" % cid)
        for fr in sprites[cid]["run"][:4] + sprites[cid]["sit"][:2]:
            h.append("    {" + ",".join(str(LEVEL[c]) for r in fr for c in r) + "},")
        h.append("  },")
    h.append("};")
    nfr = [len(a) for a in anims.values()]
    h += ["", "// Animation skins: ANIM_LEN[a] frames starting at ANIM_START[a] in ANIM_DATA (104 pixels each)",
          "static const uint16_t ANIM_LEN[ANIM_COUNT] = {%s};" % ",".join(map(str, nfr)),
          "static const uint16_t ANIM_START[ANIM_COUNT] = {%s};" % ",".join(str(sum(nfr[:i])) for i in range(len(nfr))),
          "static const uint8_t ANIM_DATA[%d][104] = {" % sum(nfr)]
    for aid, fr in anims.items():
        h.append("  // %s" % aid)
        h += ["  {" + ",".join(str(LEVEL[c]) for r in f for c in r) + "}," for f in fr]
    h += ["};", "static const char* const SPRITE_IDS[SPRITE_COUNT] = {" + ",".join('"%s"' % i for i in ids) + "};", ""]
    return js, "\n".join(h)


if __name__ == "__main__":
    js, hdr = build()
    if "--check" in sys.argv:
        ok = (os.path.exists(OUT_JSON) and open(OUT_JSON).read() == js and os.path.exists(OUT_H) and open(OUT_H).read() == hdr)
        sys.exit(0 if ok else "generated sprite files are stale: run `make sprites`")
    os.makedirs(os.path.dirname(OUT_H), exist_ok=True)
    open(OUT_JSON, "w").write(js)
    open(OUT_H, "w").write(hdr)
    print("built %d sprites" % js.count('"name"'))
